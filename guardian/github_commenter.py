
"""Publish FiberLab Guardian reports as GitHub pull request comments."""

import json
import os
import re
from dataclasses import dataclass
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

from guardian.reporter import GuardianReport


@dataclass
class GitHubCommentResult:
    """Details of a successfully published GitHub comment."""

    comment_id: int
    comment_url: str


class GitHubCommentError(Exception):
    """Raised when a Guardian comment cannot be published."""


def _validate_repository(repository: str) -> None:
    if not isinstance(repository, str) or not re.fullmatch(
        r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+",
        repository,
    ):
        raise ValueError("Repository must use the owner/repository format.")


def _validate_pr_number(pr_number: int) -> None:
    if (
        isinstance(pr_number, bool)
        or not isinstance(pr_number, int)
        or pr_number <= 0
    ):
        raise ValueError("Pull request number must be a positive integer.")


def format_guardian_comment(report: GuardianReport) -> str:
    """Format a Guardian report as a readable GitHub Markdown comment."""

    lines = [
        "## 🛡️ FiberLab Guardian Report",
        "",
        f"**Overall Status: {report.overall_status}**",
        "",
        "### Inspection Summary",
        "",
        f"- Passed: **{report.passed}**",
        f"- Failed: **{report.failed}**",
        f"- Pending: **{report.pending}**",
        "",
        "### Diagnostic Findings",
    ]

    if not report.diagnostics:
        lines.extend(["", "No diagnostic findings were generated."])

    for diagnostic in report.diagnostics:
        lines.extend(
            [
                "",
                f"#### {diagnostic.status}: `{diagnostic.file}`",
                f"- **Severity:** {diagnostic.severity}",
                f"- **Finding:** {diagnostic.message}",
                f"- **Recommendation:** {diagnostic.recommendation}",
            ]
        )

    lines.extend(
    [
        "",
        "---",
        (
            "_Generated by FiberLab Guardian. This is an automated "
            "inspection report, not an approval or merge decision._"
        ),
    ]
)

    comment = "\n".join(lines)

    if len(comment) > 60_000:
        raise ValueError(
            "Guardian report is too long to publish as one GitHub comment."
        )

    return comment


def publish_guardian_comment(
    repository: str,
    pr_number: int,
    report: GuardianReport,
    token: str | None = None,
    timeout: int = 15,
) -> GitHubCommentResult:
    """Publish a Guardian report as a top-level GitHub PR comment."""

    _validate_repository(repository)
    _validate_pr_number(pr_number)

    if isinstance(timeout, bool) or not isinstance(timeout, int) or timeout <= 0:
        raise ValueError("Timeout must be a positive integer.")

    auth_token = token or os.getenv("GITHUB_TOKEN")

    if not auth_token:
        raise ValueError(
            "GitHub token is required. Set the GITHUB_TOKEN environment variable."
        )

    comment_body = format_guardian_comment(report)

    payload = json.dumps({"body": comment_body}).encode("utf-8")

    request = Request(
        (
            "https://api.github.com/repos/"
            f"{repository}/issues/{pr_number}/comments"
        ),
        data=payload,
        headers={
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {auth_token}",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "FiberLab-Guardian",
            "Content-Type": "application/json",
        },
        method="POST",
    )

    try:
        with urlopen(request, timeout=timeout) as response:
            data = json.loads(response.read().decode("utf-8"))

    except HTTPError as error:
        if error.code in (401, 403):
            message = (
                "GitHub denied comment publishing. Check token permissions."
            )
        else:
            message = f"GitHub returned HTTP {error.code} while publishing."

        raise GitHubCommentError(message) from error

    except (URLError, TimeoutError, OSError) as error:
        raise GitHubCommentError(
            "Unable to connect to GitHub while publishing the comment."
        ) from error

    except (json.JSONDecodeError, UnicodeDecodeError) as error:
        raise GitHubCommentError(
            "GitHub returned an invalid comment response."
        ) from error

    if (
        not isinstance(data, dict)
        or not isinstance(data.get("id"), int)
        or isinstance(data.get("id"), bool)
        or not isinstance(data.get("html_url"), str)
    ):
        raise GitHubCommentError("GitHub returned an unexpected comment response.")

    return GitHubCommentResult(
        comment_id=data["id"],
        comment_url=data["html_url"],
    )
